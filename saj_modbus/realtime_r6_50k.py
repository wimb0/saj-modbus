"""R6 17-50K realtime map (0x6000-0x6080, 2022 map PDF 4.2.3).

C6 is NOT supported by this package (Modbus control issues), so this module
covers the R6 17-50K side of that shared map section only. If the reported
device type is C6, setup refuses instead of polling this map.

Two components so neither read exceeds the Modbus 125-register limit.
Note the differences vs PLUS/R5: TodayEnergy is UInt32 here (0x600A),
Power is UInt32 (0x601D), QPower is Int32 (0x601F), PV strings go to PV12.
"""

from __future__ import annotations

from modbus_connection.model import Component, gauge, integer, uint32

from .fields import DateTimeField


