    faultmsg1 = uint32(0x6016)
    faultmsg2 = uint32(0x6018)
    conntime = integer(0x601A, signed=False)
    energy = uint32(0x601B, scale=0.01)
    power = uint32(0x601D, scale=1)
    qpower0 = integer(0x601F)
    qpower1 = integer(0x6020)
    pf = gauge(0x6021, 0.001)
    l1volt = gauge(0x6022, 0.1, signed=False)
